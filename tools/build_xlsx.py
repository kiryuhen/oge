def theme_food(rng, name):
    rows = []
    for i in range(rng.randint(400, 700)):
        prod = f"{rng.choice(FOOD)}-{i + 1}"
        f, p, c = (round(rng.uniform(0, 40), 1), round(rng.uniform(0, 30), 1), round(rng.uniform(0, 75), 1))
        kcal = round(9 * f + 4 * p + 4 * c)
        rows.append([prod, f, p, c, kcal])
    header = ["продукт", "жиры, г", "белки, г", "углеводы, г", "калорийность, ккал"]
    fx, px = rng.choice([5, 10, 15]), rng.choice([5, 10, 15])
    q1 = (f"Сколько продуктов в таблице содержат **меньше {fx} г жиров** и **меньше {px} г белков**? "
          "Запишите число этих продуктов в ячейку **H2** таблицы.")
    a1 = sum(1 for r in rows if r[1] < fx and r[2] < px)
    cx = rng.choice([10, 20, 30])
    sel = [r[4] for r in rows if r[3] > cx]
    q2 = (f"Какова средняя калорийность продуктов, у которых содержание **углеводов больше {cx} г**? "
          "Ответ на этот вопрос запишите в ячейку **H3** таблицы с точностью не менее двух знаков после запятой.")
    a2 = r2(sum(sel) / len(sel))
    q3 = ("Постройте круговую диаграмму, отображающую соотношение количества продуктов, у которых "
          "калорийность **меньше 200** ккал, **от 200 до 400** ккал включительно и **больше 400** ккал. "
          "Левый верхний угол диаграммы разместите вблизи ячейки **G6**. В поле диаграммы должны присутствовать "
          "легенда и числовые значения данных, по которым построена диаграмма.")
    a3 = (f"меньше 200 — {sum(1 for r in rows if r[4] < 200)}; от 200 до 400 — "
          f"{sum(1 for r in rows if 200 <= r[4] <= 400)}; больше 400 — {sum(1 for r in rows if r[4] > 400)}")
    intro = ("В электронную таблицу занесли данные о калорийности продуктов. В столбце A записан продукт; "
             "в столбце B — содержание в нём жиров; в столбце C — содержание белков; в столбце D — содержание "
             "углеводов; в столбце E — калорийность этого продукта (все значения — на 100 г продукта).\n\n"
             f"Всего в электронную таблицу были занесены данные по {len(rows)} продуктам.")
    save(name, header, rows)
    return intro, header, rows, [(q1, str(a1)), (q2, a2), (q3, a3)]


SHOPS = ["Северный", "Южный", "Центральный", "Заречный", "Лесной"]
GOODS = [("тетрадь", 45), ("ручка", 30), ("карандаш", 15), ("линейка", 25), ("ластик", 20), ("пенал", 350),
         ("альбом", 120), ("краски", 280), ("дневник", 190), ("рюкзак", 2400)]


def theme_shop(rng, name):
    rows = []
    for _ in range(rng.randint(500, 900)):
        g, p = rng.choice(GOODS)
        rows.append([rng.choice(SHOPS), g, rng.randint(1, 30), p])
    header = ["магазин", "товар", "количество", "цена, руб."]
    s1, g1 = rng.choice(SHOPS), rng.choice(GOODS)[0]
    q1 = (f"Сколько всего единиц товара «**{g1}**» продано в магазине «**{s1}**»? Ответ на этот вопрос "
          "запишите в ячейку **H2** таблицы.")
    a1 = sum(r[2] for r in rows if r[0] == s1 and r[1] == g1)
    s2 = rng.choice(SHOPS)
    q2 = (f"В столбце **E** для каждой записи вычислите стоимость покупки (количество × цена). Какова общая "
          f"выручка магазина «**{s2}**»? Ответ на этот вопрос запишите в ячейку **H3** таблицы.")
    a2 = sum(r[2] * r[3] for r in rows if r[0] == s2)
    ch = rng.sample(SHOPS, 3)
    q3 = ("Постройте круговую диаграмму, отображающую соотношение числа записей о продажах в магазинах "
          + ", ".join(f"«{c}»" for c in ch[:-1]) + f" и «{ch[-1]}». "
          "Левый верхний угол диаграммы разместите вблизи ячейки **G6**. В поле диаграммы должны присутствовать "
          "легенда и числовые значения данных, по которым построена диаграмма.")
    a3 = "; ".join(f"{c} — {sum(1 for r in rows if r[0] == c)}" for c in ch)
    intro = ("В электронную таблицу занесли данные о продажах канцтоваров в сети магазинов. В столбце A "
             "записано название магазина; в столбце B — товар; в столбце C — количество проданных единиц; "
             "в столбце D — цена одной единицы товара (руб.).\n\n"
             f"Всего в электронную таблицу были занесены данные по {len(rows)} продажам.")
    save(name, header, rows)
    return intro, header, rows, [(q1, str(a1)), (q2, str(a2)), (q3, a3)]


