def _gaps(rng, L):
    """Позиции проходов: не у краёв и никакие два не рядом."""
    gaps = set()
    for x in range(1, L - 1):
        if x - 1 not in gaps and rng.random() < 0.3:
            gaps.add(x)
    return gaps


