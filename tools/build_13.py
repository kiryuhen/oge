def doc_requirements(d):
    has_u = "<u>" in "".join(d["paragraphs"])
    has_sub = "<sub>" in "".join(d["paragraphs"]) or "<sup>" in "".join(d["paragraphs"])
    cols = len(d["table"][0])
    rows = len(d["table"][1]) + 1
    req = (f"Создайте в текстовом редакторе документ и напишите в нём следующий текст, точно воспроизведя всё "
           f"оформление текста, имеющееся в образце.\n\n"
           f"Данный текст должен быть набран шрифтом размером **{d['fs']} пунктов** обычного начертания. "
           f"Отступ первой строки первого абзаца основного текста — **{str(d['indent']).replace('.', ',')} см**. "
           f"Расстояние между строками текста не менее одинарного, но не более полуторного междустрочного интервала.\n\n"
           f"Основной текст выровнен **по ширине**; в ключевых словах первого абзаца применено полужирное и "
           f"курсивное начертание"
           + ("; во втором абзаце одно слово подчёркнуто" if has_u else "")
           + ("; есть нижний или верхний индекс" if has_sub else "") + ".\n\n"
           f"Таблица ({rows} {'строки' if rows < 5 else 'строк'}, {cols} столбца) выровнена **по центру**; ширина таблицы меньше ширины основного "
           f"текста. Текст в первой строке таблицы — полужирный, выровнен по центру; в остальных ячейках — "
           f"выравнивание по левому краю.\n\n"
           "При этом допустимо, чтобы ширина вашего текста отличалась от ширины текста в примере, поскольку ширина "
           "текста зависит от размеров страницы и полей. В этом случае разбиение текста на строки должно "
           "соответствовать стандартной ширине абзаца.")
    return req


def doc_html(d):
    px = d["fs"] * 4 / 3
    paras = "".join(f'<p style="text-indent:{d["indent"]}cm" >{p}</p>' if i == 0 else f"<p>{p}</p>"
                    for i, p in enumerate(d["paragraphs"]))
    head, rows = d["table"]
    th = "".join(f"<th>{h}</th>" for h in head)
    trs = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f"""<!doctype html><html><head><meta charset="utf-8"><style>
body {{ margin:0; background:#fff; }}
.page {{ width:640px; padding:36px 48px; font-family:'Liberation Serif',serif; font-size:{px:.1f}px;
        line-height:1.25; color:#000; }}
p {{ text-align:justify; margin:0 0 4px 0; }}
table {{ border-collapse:collapse; margin:16px auto 0 auto; width:75%; }}
th, td {{ border:1px solid #000; padding:3px 8px; text-align:left; }}
th {{ text-align:center; font-weight:bold; }}
</style></head><body><div class="page">{paras}<table><tr>{th}</tr>{trs}</table></div></body></html>"""


def shot(html, out, w, h):
    with tempfile.NamedTemporaryFile("w", suffix=".html", delete=False, encoding="utf-8") as f:
        f.write(html)
        path = f.name
    subprocess.run([CHROME, "--headless", "--no-sandbox", "--disable-gpu", "--hide-scrollbars",
                    f"--window-size={w},{h}", f"--screenshot={out}", f"file://{path}"],
                   check=True, capture_output=True)
    os.unlink(path)
    # обрезаем белые поля снизу
    from PIL import Image, ImageChops
    im = Image.open(out).convert("RGB")
    bg = Image.new("RGB", im.size, (255, 255, 255))
    box = ImageChops.difference(im, bg).getbbox()
    if box:
        im.crop((0, 0, im.width, min(im.height, box[3] + 30))).save(out)


