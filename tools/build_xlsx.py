SUBJ = ["информатика", "математика", "физика", "химия", "биология", "история", "обществознание",
        "английский язык", "география", "литература"]


def acc(subject):
    """винительный падеж: информатика → информатику"""
    if subject.endswith("а"):
        return subject[:-1] + "у"
    if subject.endswith("я"):
        return subject[:-1] + "ю"
    return subject


def theme_test(rng, name):
    n = rng.randint(600, 1000)
    rows = [[rng.choice(DISTRICTS)[0], f"Ученик {i + 1}", rng.choice(SUBJ), rng.randint(150, 1000)]
            for i in range(n)]
    header = ["округ", "фамилия", "предмет", "баллы"]
    d1, d2 = rng.sample(DISTRICTS, 2)
    s1 = rng.choice(SUBJ)
    q1 = (f"Сколько учеников в {d1[1].replace('ый', 'ом').replace('ий', 'ем')} округе (**{d1[0]}**) выбрали "
          f"в качестве любимого предмета **{acc(s1)}**? Ответ на этот вопрос запишите в ячейку **H2** таблицы.")
    a1 = sum(1 for r in rows if r[0] == d1[0] and r[2] == s1)
    sc = [r[3] for r in rows if r[0] == d2[0]]
    q2 = (f"Каков средний тестовый балл у учеников {d2[1].replace('ый', 'ого').replace('ий', 'его')} округа "
          f"(**{d2[0]}**)? Ответ на этот вопрос запишите в ячейку **H3** таблицы с точностью не менее двух "
          f"знаков после запятой.")
    a2 = r2(sum(sc) / len(sc))
    ch = rng.sample(DISTRICTS, 3)
    q3 = ("Постройте круговую диаграмму, отображающую соотношение числа участников из округов с кодами "
          + ", ".join(f"«{c[0]}»" for c in ch[:-1]) + f" и «{ch[-1][0]}». "
          "Левый верхний угол диаграммы разместите вблизи ячейки **G6**. В поле диаграммы должны "
          "присутствовать легенда (обозначение, какой сектор диаграммы соответствует каким данным) "
          "и числовые значения данных, по которым построена диаграмма.")
    a3 = "; ".join(f"{c[0]} — {sum(1 for r in rows if r[0] == c[0])}" for c in ch)
    intro = ("В электронную таблицу занесли данные о тестировании учеников по выбранным ими предметам.\n\n"
             "В столбце A записан код округа, в котором учится ученик; в столбце B — фамилия; в столбце C — "
             "выбранный учеником предмет; в столбце D — тестовый балл.\n\n"
             f"Всего в электронную таблицу были занесены данные по {n} ученикам.")
    save(name, header, rows)
    return intro, header, rows, [(q1, str(a1)), (q2, a2), (q3, a3)]


