def theme_weather(rng, name):
    year = rng.choice([2023, 2024, 2025])
    d = datetime.date(year, 1, 1)
    rows = []
    while d.year == year:
        base = -12 + 30 * (1 - abs(d.timetuple().tm_yday - 196) / 183)
        t = round(base + rng.gauss(0, 4), 1)
        rain = round(max(0.0, rng.gauss(0, 4)), 1)
        rows.append([d, t, rain, rng.randint(728, 772), rng.choice(WIND), round(rng.uniform(0, 12), 1)])
        d += datetime.timedelta(days=1)
    header = ["дата", "температура", "осадки", "давление", "ветер", "скорость ветра"]
    m = rng.randrange(12)
    ts = [r[1] for r in rows if r[0].month == m + 1]
    q1 = (f"Какова средняя температура воздуха в **{MONTHS[m]}** {year} года? Ответ на этот вопрос запишите "
          f"в ячейку **H2** таблицы с точностью не менее двух знаков после запятой.")
    a1 = r2(sum(ts) / len(ts))
    w = rng.choice(WIND)
    sp = rng.choice([3, 4, 5, 6, 7])
    q2 = (f"Сколько дней дул **{WIND_NAME[w]}** ветер (**{w}**) со скоростью **более {sp} м/с**? Ответ на этот "
          f"вопрос запишите в ячейку **H3** таблицы.")
    a2 = sum(1 for r in rows if r[4] == w and r[5] > sp)
    ch = rng.sample(WIND, 3)
    q3 = ("Постройте круговую диаграмму, отображающую соотношение количества дней, когда дул ветер направлений "
          + ", ".join(f"«{c}»" for c in ch[:-1]) + f" и «{ch[-1]}». "
          "Левый верхний угол диаграммы разместите вблизи ячейки **G6**. В поле диаграммы должны присутствовать "
          "легенда и числовые значения данных, по которым построена диаграмма.")
    a3 = "; ".join(f"{c} — {sum(1 for r in rows if r[4] == c)}" for c in ch)
    intro = (f"В электронную таблицу занесли данные наблюдения за погодой в течение {year} года. "
             "В столбце A записана дата наблюдения, в столбце B — среднесуточная температура воздуха (°C), "
             "в столбце C — количество осадков (мм), в столбце D — атмосферное давление (мм рт. ст.), "
             "в столбце E — направление ветра, в столбце F — средняя скорость ветра (м/с).\n\n"
             f"Всего в таблицу были занесены данные по {len(rows)} дням.")
    save(name, header, rows)
    return intro, header, rows, [(q1, a1), (q2, str(a2)), (q3, a3)]


