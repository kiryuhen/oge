def save(name, header, rows):
    wb = Workbook()
    ws = wb.active
    ws.title = "Лист1"
    ws.append(header)
    for c in ws[1]:
        c.font = Font(bold=True)
    for r in rows:
        ws.append(r)
    for col, w in zip("ABCDEFGH", [14, 16, 14, 12, 12, 12, 12, 12]):
        ws.column_dimensions[col].width = w
    wb.save(os.path.join(OUT, name))


def r2(x):
    return f"{x:.2f}".replace(".", ",")


def first_rows_md(header, rows, n=5):
    cols = "ABCDEFGH"[:len(header)]
    out = "|   | " + " | ".join(cols) + " |\n|---|" + "---|" * len(cols) + "\n"
    out += "| **1** | " + " | ".join(f"**{h}**" for h in header) + " |\n"
    for i, r in enumerate(rows[:n - 1]):
        cells = []
        for x in r:
            if isinstance(x, datetime.date):
                x = x.strftime("%d.%m.%Y")
            elif isinstance(x, float):
                x = str(x).replace(".", ",")
            cells.append(str(x))
        out += f"| **{i + 2}** | " + " | ".join(cells) + " |\n"
    return out


