# ---------------------------------------------------------------- проверка и картинки

def check(t, runs=300, seed=0):
    rng = random.Random(seed)
    for _ in range(runs):
        args = {k: g(rng) for k, g in t["params"].items()}
        f, need = t["build"](**args)
        run(t["solution"], f)
        if f.painted != need:
            extra, miss = f.painted - need, need - f.painted
            raise AssertionError(f"{t['id']} {args}: лишние {sorted(extra)}, не закрашены {sorted(miss)}")


def example(t, seed=7):
    rng = random.Random(seed)
    args = {k: g(rng) for k, g in t["params"].items()}
    # для картинки — среднего размера
    for k in args:
        if k != "seed":
            args[k] = max(args[k], {"p": 2, "D": 2}.get(k, 3))
    f, need = t["build"](**args)
    return f, need


def render_all():
    os.makedirs(IMG, exist_ok=True)
    for t in TASKS:
        f, need = example(t)
        with open(os.path.join(IMG, f"{t['id']}-before.svg"), "w") as fh:
            fh.write(svg(f, painted=set()))
        with open(os.path.join(IMG, f"{t['id']}-after.svg"), "w") as fh:
            fh.write(svg(f, painted=need, robot=False))


if __name__ == "__main__":
    for t in TASKS:
        check(t)
        print("OK", t["id"], t["title"])
    render_all()
    print("картинки:", IMG)
